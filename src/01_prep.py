CBAM_RX = [(k, re.compile(i), re.compile(e)) for k, i, e in CBAM]

def norm(s):
    return unicodedata.normalize('NFKC', str(s)).upper().replace(' ', '')

def classify(rx_list, prod, default):
    p = norm(prod)
    if not p:
        return '미분류'
    for item in rx_list:
        if len(item) == 3:
            k, inc, exc = item
            if inc.search(p) and not exc.search(p):
                return k
        else:
            k, inc = item
            if inc.search(p):
                return k
    return default

def parse_addr(a):
    a = str(a).strip()
    if not a:
        return ('미상', '미상')
    head = a.split()[0]
    sido = SIDO.get(head)
    if sido is None:
        for k, v in SIDO.items():
            if a.startswith(k):
                sido = v; break
    if sido is None:
        return ('미상', '미상')
    rest = a[len(head):].strip() if head in SIDO else a
    toks = rest.split()
    sgg = toks[0] if toks else ''
    if len(toks) > 1 and toks[0].endswith('시') and toks[1].endswith('구'):
        sgg = toks[0] + ' ' + toks[1]
    if not sgg or not re.search(r'(시|군|구)$', sgg.split()[-1]):
        sgg = '미상'
    return (sido, sgg)

def main():
    df = pd.read_csv(SRC, encoding='cp949', dtype=str).fillna('')
    for c in df.columns:
        df[c] = df[c].str.strip()

    df['시도'], df['시군구'] = zip(*df['공장주소'].map(parse_addr))
    df['단지'] = df['단지명'].replace('', '(개별입지)')
    df['단지유형'] = df['단지명'].map(cx_type)
    df['입지'] = df['단지명'].apply(lambda x: '산업단지' if x else '개별입지')
    df['업종'] = df['생산품'].map(lambda p: classify(SECT_RX, p, '기타 제조'))
    df['열공정'] = df['생산품'].map(lambda p: classify(HEAT_RX, p, '해당없음'))
    df.loc[df['열공정'] == '미분류', '열공정'] = '해당없음'
    df['CBAM'] = df['생산품'].map(lambda p: classify(CBAM_RX, p, ''))
    df.loc[df['CBAM'].isin(['미분류']), 'CBAM'] = ''

    df.to_pickle(paths.CLEAN)

    print(f"\n총 {len(df):,}건")
